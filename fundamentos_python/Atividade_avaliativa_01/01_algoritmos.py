#Questão 1: Descreva o conceito de algoritmos.


#Um algoritmo é um conjunto finito de regras e instruções bem definidas que, quando seguidas em ordem lógica, processam dados de entrada para gerar um resultado ou resolver um problema. Um exemplo do dia a dia é uma receita de bolo: ela possui os ingredientes (entradas), o passo a passo ordenado (processamento) e o bolo pronto (saída).