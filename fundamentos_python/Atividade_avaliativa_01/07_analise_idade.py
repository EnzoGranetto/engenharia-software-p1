#Questão 7: Escreva um programa em Python que receba a idade de uma pessoa e informe se ela é maior de idade. Para isso, a pessoa deve possuir idade maior ou igual a 18 anos.


#Entrada de dados
x = int(input("Qual é a sua idade? "))

if x >= 18:
  print("Você é maior de idade!")
else:
  print("Você é de menor!")